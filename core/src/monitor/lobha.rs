//! # Lobha — โลภเจตสิกในฐานะ `struct` ของ Rust
//!
//! ## หลักการ
//!
//! ไฟล์นี้ **ไม่ใช่** การจำลองโลภเจตสิก
//! แต่เป็นการ **อธิบาย** ว่า `struct` ใน Rust
//! ทำงาน **เหมือน** เจตสิกอย่างไร
//!
//! เราไม่ได้สร้าง "โลภะ" ขึ้นมา
//! เราแค่ **เห็น** ว่า `struct` มีลักษณะ **ตรงกับ** เจตสิก
//!
//! ---
//!
//! ## ลักษณะของเจตสิกในอภิธรรม
//!
//! เจตสิกมีลักษณะ 4 ประการ:
//!
//! 1. **ลักษณณะ** (lakkhana) — ลักษณะเฉพาะ
//! 2. **รสะ** (rasa) — กิจ
//! 3. **ปัจจุปัฏฐาน** (paccupaṭṭhāna) — การปรากฏ
//! 4. **ปทัฏฐาน** (padaṭṭhāna) — เหตุใกล้
//!
//! ## ลักษณะของ `struct` ใน Rust
//!
//! `struct` มีลักษณะ 4 ประการ:
//!
//! 1. **ชื่อ struct** — ลักษณะเฉพาะ
//! 2. **field** — กิจ
//! 3. **impl** — การปรากฏ
//! 4. **constructor** — เหตุใกล้
//!
//! ## การเห็น
//!
//! เมื่อเห็นว่า `struct` = เจตสิก — คุณจะ **ไม่เขียน "เจตสิก"**
//! แต่จะ **ใช้ `struct`** เพื่อทำงานที่เจตสิกทำ
//!
//! ---

// =========================================================
// 1. ชื่อ struct = ลักษณณะ (ลักษณะเฉพาะ)
// =========================================================

/// **ชื่อ struct = ลักษณณะ** — ลักษณะเฉพาะ
///
/// ในอภิธรรม โลภะมีลักษณณะ = "ความยึดติดในอารมณ์"
/// ใน Rust ชื่อ struct = "ชื่อของสิ่งนั้น"
///
/// ทั้งสอง — **คือการระบุตัวตน** — ว่า "นี่คืออะไร"
///
/// ## ตัวอย่าง
///
/// ```
/// // ชื่อ struct = ลักษณณะ
/// // Lobha = "ความยึดติด"
/// ```
pub struct Lobha;

// =========================================================
// 2. field = รสะ (กิจ)
// =========================================================

/// **field = รสะ** — กิจ
///
/// ในอภิธรรม โลภะมีรสะ = "ไม่ปล่อยวาง"
/// ใน Rust field = "สิ่งที่ struct ทำ"
///
/// ทั้งสอง — **คือการทำงาน** — ว่า "ทำอะไร"
///
/// ## ตัวอย่าง
///
/// ```ignore
/// pub struct Lobha {
///     object: String,     // ยึดอะไร
///     grasped: bool,      // ยึดหรือยัง
/// }
/// ```
///
/// **หมายเหตุ:** เราไม่ได้ประกาศ field จริง
/// เพราะเราแค่ **อธิบาย** ว่า field = รสะ
/// ไม่ใช่ **จำลอง** รสะ
pub struct LobhaWithFields {
    /// **field = รสะ** — สิ่งที่โลภะยึด
    pub object: String,
    /// **field = รสะ** — สภาพของการยึด
    pub grasped: bool,
}

// =========================================================
// 3. impl = ปัจจุปัฏฐาน (การปรากฏ)
// =========================================================

/// **impl = ปัจจุปัฏฐาน** — การปรากฏ
///
/// ในอภิธรรม โลภะมีปัจจุปัฏฐาน = "การไม่สละ"
/// ใน Rust `impl` = "สิ่งที่ struct ทำได้"
///
/// ทั้งสอง — **คือการแสดงออก** — ว่า "ปรากฏอย่างไร"
impl LobhaWithFields {
    /// **method = ปัจจุปัฏฐาน** — การปรากฏ
    ///
    /// โลภะปรากฏโดย "การยึด"
    /// method ปรากฏโดย "การเรียก"
    pub fn grasp(&mut self) {
        self.grasped = true;
    }

    /// **method = ปัจจุปัฏฐาน** — การปรากฏ
    ///
    /// โลภะปรากฏโดย "การไม่ปล่อย"
    /// method ปรากฏโดย "การถาม"
    pub fn is_grasping(&self) -> bool {
        self.grasped
    }
}

// =========================================================
// 4. constructor = ปทัฏฐาน (เหตุใกล้)
// =========================================================

/// **constructor = ปทัฏฐาน** — เหตุใกล้
///
/// ในอภิธรรม โลภะมีปทัฏฐาน = "อารมณ์ที่น่าพอใจ"
/// ใน Rust `constructor` = "สิ่งที่ต้องมีก่อนสร้าง"
///
/// ทั้งสอง — **คือเหตุ** — ว่า "ต้องมีอะไรก่อน"
impl LobhaWithFields {
    /// **constructor = ปทัฏฐาน** — เหตุใกล้
    ///
    /// โลภะเกิดได้เพราะ "อารมณ์ที่น่าพอใจ"
    /// struct สร้างได้เพราะ "object"
    pub fn new(object: impl Into<String>) -> Self {
        Self {
            object: object.into(),
            grasped: false,
        }
    }
}

// =========================================================
// 5. TESTS — พิสูจน์ว่า "struct = เจตสิก"
// =========================================================

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn struct_name_is_lakkhana() {
        // ชื่อ struct = ลักษณณะ
        // Lobha = "ความยึดติด"
        // ไม่มี test — เพราะชื่อ struct มีอยู่แล้ว
        // แต่เรา "เห็น" ว่ามัน = ลักษณณะ
    }

    #[test]
    fn field_is_rasa() {
        // field = รสะ
        let lobha = LobhaWithFields::new("gold");
        assert_eq!(lobha.object, "gold");
        assert!(!lobha.grasped);
    }

    #[test]
    fn impl_is_paccupatthana() {
        // impl = ปัจจุปัฏฐาน
        let mut lobha = LobhaWithFields::new("gold");
        lobha.grasp();
        assert!(lobha.is_grasping());
    }

    #[test]
    fn constructor_is_padatthana() {
        // constructor = ปทัฏฐาน
        // Lobha เกิดเพราะ "อารมณ์ที่น่าพอใจ"
        // struct สร้างเพราะ "object"
        let lobha = LobhaWithFields::new("gold");
        assert_eq!(lobha.object, "gold");
    }

    #[test]
    fn struct_is_cetasika() {
        // struct ทั้งหมด = เจตสิก
        let mut lobha = LobhaWithFields::new("gold");
        assert!(!lobha.is_grasping());
        lobha.grasp();
        assert!(lobha.is_grasping());
    }
}
